"""
Generate drugs.h for the microcontroller from drug_table.csv,
results_all.csv and the ML model.

Each drug entry carries:
  - name, Cmax (nM)
  - IC50 and Hill coefficient for hERG / INa / ICaL
  - precomputed dAPD90 at 1x and 10x Cmax (for on-screen display)
  - a flag saying whether the hERG value was measured or ML-predicted
"""
import numpy as np
import pandas as pd

MAX_NAME = 15          # chars shown on the device
NOBLOCK = 1e12

drugs = pd.read_csv("drug_table.csv")
try:
    res = pd.read_csv("results_all.csv")
except FileNotFoundError:
    res = None
    print("results_all.csv not found - dAPD90 fields will be 0")


def apd_at(drug, dose, variant="measured"):
    if res is None:
        return 0.0
    row = res[(res.drug == drug) & (res.dose_x == dose) &
              (res.variant == variant)]
    if len(row) == 0 or pd.isna(row.iloc[0]["dAPD90_pct"]):
        return float("nan")
    return float(row.iloc[0]["dAPD90_pct"])


def _lit(x):
    """Format a number as a VALID C float literal (needs a '.' or exponent)."""
    s = f"{x:.6g}"
    if "e" not in s and "E" not in s and "." not in s:
        s += ".0"
    return s + "f"


def cfloat(x):
    """IC50 / Cmax literal; missing or huge values become the no-block sentinel."""
    if x is None or (isinstance(x, float) and (np.isnan(x) or np.isinf(x))):
        return "1e12f"
    if x >= 1e11:
        return "1e12f"
    return _lit(x)


def capd(x):
    """APD literal; missing means the cell failed to capture -> NaN, not a number."""
    if x is None or (isinstance(x, float) and (np.isnan(x) or np.isinf(x))):
        return "NAN"
    return _lit(x)


lines = []
lines.append("/* drugs.h - generated by export_drugs_h.py. Do not edit by hand. */")
lines.append("#ifndef DRUGS_H")
lines.append("#define DRUGS_H")
lines.append("")
lines.append("#include <stdint.h>")
lines.append("#include <math.h>   /* NAN, for drugs with no capture */")
lines.append("")
lines.append("/* Channel order used throughout: 0 = hERG (IK), 1 = INa, 2 = ICaL */")
lines.append("#define DRUG_CH_HERG  0")
lines.append("#define DRUG_CH_INA   1")
lines.append("#define DRUG_CH_ICAL  2")
lines.append("#define DRUG_N_CH     3")
lines.append("")
lines.append("/* Doses offered in the UI, as multiples of therapeutic Cmax */")
lines.append("#define DRUG_N_DOSE   4")
lines.append("static const float DRUG_DOSES[DRUG_N_DOSE] = {1.0f, 4.0f, 10.0f, 30.0f};")
lines.append("")
lines.append("typedef struct {")
lines.append("    const char *name;")
lines.append("    float cmax;             /* nM, free therapeutic plasma conc */")
lines.append("    float ic50[DRUG_N_CH];  /* nM */")
lines.append("    float hill[DRUG_N_CH];")
lines.append("    float dapd90_1x;        /* %% change vs control, NaN if no capture */")
lines.append("    float dapd90_10x;")
lines.append("    uint8_t predicted;      /* 1 = hERG IC50 came from the ML model */")
lines.append("    uint8_t risk;           /* 0 low, 1 intermediate, 2 high */")
lines.append("} Drug;")
lines.append("")

RISK = {"low": 0, "intermediate": 1, "high": 2}
entries = []
for _, d in drugs.sort_values("drug").iterrows():
    name = str(d["drug"])[:MAX_NAME]
    a1, a10 = apd_at(d["drug"], 1), apd_at(d["drug"], 10)
    entries.append(
        f'    {{"{name}", {cfloat(d["cmax"])}, '
        f'{{{cfloat(d["hERG_IC50"])}, {cfloat(d["INa_IC50"])}, {cfloat(d["ICaL_IC50"])}}}, '
        f'{{{_lit(d["hERG_h"])}, {_lit(d["INa_h"])}, {_lit(d["ICaL_h"])}}}, '
        f'{capd(a1)}, {capd(a10)}, 0, {RISK.get(d["risk"], 0)}}},'
    )

lines.append(f"#define DRUG_COUNT {len(entries)}")
lines.append("static const Drug DRUGS[DRUG_COUNT] = {")
lines.extend(entries)
lines.append("};")
lines.append("")
lines.append("#endif /* DRUGS_H */")

open("drugs.h", "w").write("\n".join(lines) + "\n")
size = sum(4 + 4 + 12 + 12 + 4 + 4 + 2 for _ in entries)
print(f"Wrote drugs.h with {len(entries)} drugs (~{size} bytes of table + name strings)")
